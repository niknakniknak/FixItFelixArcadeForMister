module jtfelix_video(
    input             rst,
    input             clk,
    input             pxl_cen,
    input             cpu_a0,
    input             bgram_we,
    input             fgram_we,
    input             fg_page,
    input             fg_cpage,
    input             fg_both,
    input             bg_page,
    input             bg_cpage,
    input             bg_both,
    input             obj_cmode,
    input             obj_commit,
    output            obj_pending,
    output     [ 7:0] bgram_dout,
    output     [ 7:0] fgram_dout,
    output     [ 1:0] bg0c_we,
    output     [ 1:0] bg1c_we,
    output     [ 1:0] fg0c_we,
    output     [ 1:0] fg1c_we,
    input      [15:0] bg0c_dout,
    input      [15:0] bg1c_dout,
    input      [15:0] fg0c_dout,
    input      [15:0] fg1c_dout,
    output     [10:0] bgmap_addr,
    output     [10:0] fgmap_addr,
    input      [15:0] bg0_dout,
    input      [15:0] bg1_dout,
    input      [15:0] fg0_dout,
    input      [15:0] fg1_dout,
    output     [ 9:0] oram_addr,
    input      [ 7:0] oram_dout,
    input      [ 8:0] scry,
    input      [ 7:0] scrx,
    input             flip,
    input             bg_en,
    input             fg_en,
    input             obj_en,
    output            LHBL,
    output            LVBL,
    output            HS,
    output            VS,
    output reg        vint,
    output     [13:0] bgrom_addr,
    output            bgrom_cs,
    input      [31:0] bgrom_data,
    input             bgrom_ok,
    output     [13:0] fgrom_addr,
    output            fgrom_cs,
    input      [31:0] fgrom_data,
    input             fgrom_ok,
    output     [15:0] obj_addr,
    output            obj_cs,
    input      [31:0] obj_data,
    input             obj_ok,
    output     [ 9:0] pal_addr,
    input      [15:0] pal_data,
    output     [ 4:0] red,
    output     [ 4:0] green,
    output     [ 4:0] blue,
    input      [ 3:0] gfx_en
);

wire [8:0] hdump, vdump, vrender, vrender1, bg_pxl, fg_pxl;
wire [9:0] obj_pxl;
wire       preLHBL, preLVBL, preHS, preVS, unused_hinit, unused_vinit, unused_video;

assign unused_video = &{ 1'b0, unused_hinit, unused_vinit };

always @(posedge clk) begin
    if( rst )
        vint <= 0;
    else
        vint <= pxl_cen && hdump==9'd438 && vdump==9'd239;
end

jtframe_vtimer #(
    .V_START    ( 9'd0      ),
    .VB_START   ( 9'd239    ),
    .VB_END     ( 9'd261    ),
    .VS_START   ( 9'd243    ),
    .VS_END     ( 9'd246    ),
    .VCNT_END   ( 9'd261    ),
    .HCNT_START ( 9'd0      ),
    .HCNT_END   ( 9'd438    ),
    .HB_START   ( 9'd319    ),
    .HB_END     ( 9'd438    ),
    .HS_START   ( 9'd356    ),
    .HS_END     ( 9'd393    ),
    .H_VB       ( 9'd438    ),
    .H_VS       ( 9'd356    ),
    .H_VNEXT    ( 9'd438    ),
    .HINIT      ( 9'd438    )
) u_timer(
    .clk        ( clk             ),
    .pxl_cen    ( pxl_cen         ),
    .vdump      ( vdump           ),
    .vrender    ( vrender         ),
    .vrender1   ( vrender1        ),
    .H          ( hdump           ),
    .Hinit      ( unused_hinit    ),
    .Vinit      ( unused_vinit    ),
    .LHBL       ( preLHBL         ),
    .LVBL       ( preLVBL         ),
    .HS         ( preHS           ),
    .VS         ( preVS           )
);

jtfelix_tiles u_tiles(
    .rst        ( rst             ),
    .clk        ( clk             ),
    .pxl_cen    ( pxl_cen         ),
    .hs         ( preHS           ),
    .hdump      ( hdump           ),
    .vrender    ( vrender         ),
    .flip       ( flip            ),
    .scry       ( scry            ),
    .scrx       ( scrx            ),
    .cpu_a0     ( cpu_a0          ),
    .bgram_we   ( bgram_we        ),
    .fgram_we   ( fgram_we        ),
    .fg_page    ( fg_page         ),
    .fg_cpage   ( fg_cpage        ),
    .fg_both    ( fg_both         ),
    .bg_page    ( bg_page         ),
    .bg_cpage   ( bg_cpage        ),
    .bg_both    ( bg_both         ),
    .bgram_dout ( bgram_dout      ),
    .fgram_dout ( fgram_dout      ),
    .bg0c_we    ( bg0c_we         ),
    .bg1c_we    ( bg1c_we         ),
    .fg0c_we    ( fg0c_we         ),
    .fg1c_we    ( fg1c_we         ),
    .bg0c_dout  ( bg0c_dout       ),
    .bg1c_dout  ( bg1c_dout       ),
    .fg0c_dout  ( fg0c_dout       ),
    .fg1c_dout  ( fg1c_dout       ),
    .bgmap_addr ( bgmap_addr      ),
    .fgmap_addr ( fgmap_addr      ),
    .bg0_dout   ( bg0_dout        ),
    .bg1_dout   ( bg1_dout        ),
    .fg0_dout   ( fg0_dout        ),
    .fg1_dout   ( fg1_dout        ),
    .bgrom_addr ( bgrom_addr      ),
    .bgrom_cs   ( bgrom_cs        ),
    .bgrom_data ( bgrom_data      ),
    .bgrom_ok   ( bgrom_ok        ),
    .fgrom_addr ( fgrom_addr      ),
    .fgrom_cs   ( fgrom_cs        ),
    .fgrom_data ( fgrom_data      ),
    .fgrom_ok   ( fgrom_ok        ),
    .bg_pxl     ( bg_pxl          ),
    .fg_pxl     ( fg_pxl          )
);

jtfelix_obj u_obj(
    .rst        ( rst             ),
    .clk        ( clk             ),
    .pxl_cen    ( pxl_cen         ),
    .flip       ( flip            ),
    .hdump      ( hdump           ),
    .vrender    ( vrender1        ),
    .LHBL       ( preLHBL         ),
    .HS         ( preHS           ),
    .ram_addr   ( oram_addr       ),
    .ram_dout   ( oram_dout       ),
    .cmode      ( obj_cmode       ),
    .commit     ( obj_commit      ),
    .pending    ( obj_pending     ),
    .rom_addr   ( obj_addr        ),
    .rom_cs     ( obj_cs          ),
    .rom_data   ( obj_data        ),
    .rom_ok     ( obj_ok          ),
    .pxl        ( obj_pxl         )
);

jtfelix_colmix u_colmix(
    .rst        ( rst             ),
    .clk        ( clk             ),
    .pxl_cen    ( pxl_cen         ),
    .preLHBL    ( preLHBL         ),
    .preLVBL    ( preLVBL         ),
    .preHS      ( preHS           ),
    .preVS      ( preVS           ),
    .bg_pxl     ( bg_pxl          ),
    .fg_pxl     ( fg_pxl          ),
    .obj_pxl    ( obj_pxl         ),
    .bg_en      ( bg_en           ),
    .fg_en      ( fg_en           ),
    .obj_en     ( obj_en          ),
    .gfx_en     ( gfx_en          ),
    .pal_addr   ( pal_addr        ),
    .pal_data   ( pal_data        ),
    .LHBL       ( LHBL            ),
    .LVBL       ( LVBL            ),
    .HS         ( HS              ),
    .VS         ( VS              ),
    .red        ( red             ),
    .green      ( green           ),
    .blue       ( blue            )
);

endmodule

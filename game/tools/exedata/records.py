ANIM_BASE = 0x419800


def anim_imm(name, va, off=3):
    return {"name": name, "kind": "imm", "va": va, "off": off, "type": "u32",
            "xf": [["sub", ANIM_BASE], ["div", 12]]}


def imm(name, va, off, typ, xf=None):
    r = {"name": name, "kind": "imm", "va": va, "off": off, "type": typ}
    if xf:
        r["xf"] = xf
    return r


def calc_rec(name, op, frm, xf=None):
    r = {"name": name, "kind": "calc", "op": op, "from": frm}
    if xf:
        r["xf"] = xf
    return r


